/// `src/saltcorn/hooks.ts`: a row type and a hook set **per table**, over the
/// generated client.
///
/// This is the file that justifies generating the runtime instead of shipping it
/// as an npm package (§2.1): `useTasks()` returns `TasksRow[]`, and `TasksRow`
/// comes from this app's own columns. A registry package could only offer
/// `useRows("tasks"): unknown[]`, which is the part worth having thrown away.
///
/// The cache is deliberately tiny: one version counter per table, bumped by any
/// mutation of that table, with `useSyncExternalStore` re-running the affected
/// queries. That is the whole invalidation model a per-table REST API needs, and
/// it is why no query library is a dependency.
fn hooks_ts(tables: &[Table], endpoints: &EndpointSet) -> String {
    let mut out = String::from(GENERATED_HEADER);
    out.push_str(
        r#"
import { useCallback, useEffect, useState, useSyncExternalStore } from "react";
import { createClient, type ApiClient } from "./client";

/** The app's typed API client. Endpoint paths already include the API mount. */
export const api: ApiClient = createClient();

/** The state of one read: data, plus what is happening to it. */
export type Query<T> = {
  data: T | undefined;
  error: Error | undefined;
  loading: boolean;
  /** Re-run this query (and any other on the same table). */
  refresh: () => void;
};

/** The state of one write. */
export type Mutation<A> = {
  run: (arg: A) => Promise<void>;
  pending: boolean;
  error: Error | undefined;
};

// One version counter per table: every read subscribes to its table, every
// write bumps it. Keys are table names, which the server already guarantees to
// be unique — there is no query-key scheme to invent or get wrong.
const versions = new Map<string, number>();
const listeners = new Map<string, Set<() => void>>();

function versionOf(table: string): number {
  return versions.get(table) ?? 0;
}

function subscribe(table: string, listener: () => void): () => void {
  const set = listeners.get(table) ?? new Set<() => void>();
  listeners.set(table, set);
  set.add(listener);
  return () => set.delete(listener);
}

/** Discard what is cached for `table`, re-running every query over it. */
export function invalidate(table: string): void {
  versions.set(table, versionOf(table) + 1);
  listeners.get(table)?.forEach((l) => l());
}

/**
 * Read something from the API, cached under `table` and re-run whenever anything
 * writes to that table.
 *
 * Exported because the per-table hooks below cannot cover a custom endpoint, and
 * an app that adds one should be able to join the same cache rather than build a
 * second one beside it.
 */
export function useQuery<T>(table: string, load: () => Promise<T>): Query<T> {
  const version = useSyncExternalStore(
    (cb) => subscribe(table, cb),
    () => versionOf(table),
    () => 0,
  );
  const [state, setState] = useState<{
    data: T | undefined;
    error: Error | undefined;
    loading: boolean;
  }>({ data: undefined, error: undefined, loading: true });

  useEffect(() => {
    let cancelled = false;
    setState((s) => ({ ...s, loading: true }));
    load().then(
      (data) => !cancelled && setState({ data, error: undefined, loading: false }),
      (e: unknown) =>
        !cancelled &&
        setState({
          data: undefined,
          error: e instanceof Error ? e : new Error(String(e)),
          loading: false,
        }),
    );
    return () => {
      cancelled = true;
    };
    // `load` closes over its arguments and is rebuilt every render; the query is
    // keyed by the table's version, which is what actually changes the answer.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [table, version]);

  return { ...state, refresh: () => invalidate(table) };
}

/**
 * Write through `fn`, then invalidate `table` so every query over it re-runs.
 * Exported for the same reason as `useQuery`.
 */
export function useMutation<A>(table: string, fn: (arg: A) => Promise<unknown>): Mutation<A> {
  const [pending, setPending] = useState(false);
  const [error, setError] = useState<Error | undefined>(undefined);
  const run = useCallback(
    async (arg: A) => {
      setPending(true);
      setError(undefined);
      try {
        await fn(arg);
        invalidate(table);
      } catch (e: unknown) {
        setError(e instanceof Error ? e : new Error(String(e)));
      } finally {
        setPending(false);
      }
    },
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [table],
  );
  return { run, pending, error };
}
"#,
    );

    for table in exposed_tables(tables, endpoints) {
        out.push('\n');
        out.push_str(&table_hooks(table, endpoints));
    }
    out
}

/// The hooks for one table: its row type, the list query, and one mutation per
/// write **the app's API actually projects**.
///
/// Each hook is emitted only when the client has the method it calls. Asking the
/// endpoint set rather than re-deriving the rule (a keyless table has no
/// row-addressed endpoints, an unexposed table has none at all) is what keeps the
/// two halves of the runtime from disagreeing.
fn table_hooks(table: &Table, endpoints: &EndpointSet) -> String {
    let name = &table.name;
    let pascal = pascal(name);
    let row = format!("{pascal}Row");
    let fields = table
        .fields
        .iter()
        .map(|f| {
            let optional = if f.required { "" } else { "?" };
            let null = if f.required { "" } else { " | null" };
            format!(
                "  {}{optional}: {}{null};",
                f.base.name,
                ts_type(basic_type(f))
            )
        })
        .collect::<Vec<_>>()
        .join("\n");

    let list = op_name("list", name);
    let mut out = format!(
        r#"// --- {name} ---

/** A row of `{name}`, as its columns are today. */
export type {row} = {{
{fields}
}};

/** Every row of `{name}`, re-fetched when anything writes to it. */
export function use{pascal}(): Query<{row}[]> {{
  return useQuery("{name}", () => api.{list}() as Promise<{row}[]>);
}}
"#
    );

    if has_op(endpoints, "create", name) {
        let create = op_name("create", name);
        out.push_str(&format!(
            r#"
/** Insert a row into `{name}`. */
export function useCreate{pascal}(): Mutation<Partial<{row}>> {{
  return useMutation("{name}", (body) => api.{create}(body));
}}
"#
        ));
    }

    // Row-addressed operations: the API projects these only for a table with a
    // single-column primary key, so the hooks follow the endpoints rather than
    // re-deciding it.
    if let Some(pk) = single_pk(table) {
        let pk_ty = table
            .fields
            .iter()
            .find(|f| f.base.name == pk)
            .map_or("string", |f| ts_type(basic_type(f)));
        out.push_str(&format!(
            r#"
/** One row of `{name}`, selected from the list by its primary key. */
export function use{pascal}Row(id: {pk_ty}): Query<{row} | undefined> {{
  const rows = use{pascal}();
  return {{ ...rows, data: rows.data?.find((r) => r.{pk} === id) }};
}}
"#
        ));
        if has_op(endpoints, "update", name) {
            let update = op_name("update", name);
            out.push_str(&format!(
                r#"
/** Replace a row of `{name}`. */
export function useUpdate{pascal}(): Mutation<{{ id: {pk_ty}; body: Partial<{row}> }}> {{
  return useMutation("{name}", ({{ id, body }}) => api.{update}(id, body));
}}
"#
            ));
        }
        if has_op(endpoints, "delete", name) {
            let delete = op_name("delete", name);
            out.push_str(&format!(
                r#"
/** Delete a row of `{name}`. */
export function useDelete{pascal}(): Mutation<{pk_ty}> {{
  return useMutation("{name}", (id) => api.{delete}(id));
}}
"#
            ));
        }
    }
    out
}

// --- naming and type helpers ------------------------------------------------

/// `blog_posts` → `BlogPosts`, matching [`op_name`]'s capitalisation so a hook
/// and the endpoint it calls are named from the same rule.
pub fn pascal(name: &str) -> String {
    op_name("", name)
}

/// A human-facing heading for a table: `blog_posts` → `Blog posts`.
fn title(name: &str) -> String {
    let mut words = name
        .split(|c: char| !c.is_alphanumeric())
        .filter(|w| !w.is_empty());
    let mut out = String::new();
    if let Some(first) = words.next() {
        let mut chars = first.chars();
        if let Some(c) = chars.next() {
            out.extend(c.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    for word in words {
        out.push(' ');
        out.push_str(word);
    }
    out
}

/// The table's single primary-key column, or `None` when its rows are not
/// addressable (no key, or a composite one).
fn single_pk(table: &Table) -> Option<String> {
    match table.primary_key.as_slice() {
        [pk] => Some(pk.clone()),
        _ => None,
    }
}

fn basic_type(field: &sc_catalog::DataField) -> BasicType {
    field
        .base
        .type_
        .as_basic()
        .cloned()
        .unwrap_or(BasicType::Text)
}

/// The TypeScript type a column's values arrive as over JSON.
fn ts_type(ty: BasicType) -> &'static str {
    match ty {
        BasicType::Bool => "boolean",
        BasicType::Int | BasicType::Float => "number",
        BasicType::Json => "unknown",
        // Decimal, uuid, dates and times all cross the wire as strings.
        _ => "string",
    }
}

/// The empty value a create form starts a column at.
fn ts_empty(field: &sc_catalog::DataField) -> &'static str {
    match basic_type(field) {
        BasicType::Bool => "false",
        BasicType::Int | BasicType::Float | BasicType::Decimal => "0",
        _ => "\"\"",
    }
}

