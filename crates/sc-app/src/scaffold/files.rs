/// `tsc --noEmit` runs *before* `vite build` in the build script on purpose: the
/// client is regenerated from the app's endpoints on every build, so a table
/// removed in the admin UI should fail the build with a type error naming the
/// call site, not produce a bundle that 404s at runtime.
const VITE_CONFIG: &str = "import { defineConfig } from \"vite\";\n\
                           import react from \"@vitejs/plugin-react\";\n\n\
                           export default defineConfig({\n\
                           \x20 plugins: [react()],\n\
                           });\n";

/// The project's TypeScript configuration.
///
/// With `graphql`, it also carries the **`gql.tada` plugin** pointed at the
/// emitted `schema.graphql` (decision 7). Nothing is added to `package.json` for
/// it: a `plugins` entry is a *language service* setting that `tsc` ignores
/// entirely, so the project builds identically with or without the package
/// installed, and a developer who wants their queries type-checked in the editor
/// installs `gql.tada` themselves and finds it already configured. Which is the
/// whole arrangement: no codegen step, and the app's dependencies stay the
/// developer's business.
fn tsconfig(graphql: bool) -> String {
    let plugins = if graphql {
        format!(
            r#",
    "plugins": [
      {{
        "name": "gql.tada/ts-plugin",
        "schema": "./{REACT_RUNTIME_SUBDIR}/{GRAPHQL_SCHEMA_FILE}",
        "tadaOutputLocation": "./{REACT_RUNTIME_SUBDIR}/graphql-env.d.ts"
      }}
    ]"#
        )
    } else {
        String::new()
    };
    format!(
        r#"{{
  "compilerOptions": {{
    "target": "ES2022",
    "lib": ["ES2022", "DOM", "DOM.Iterable"],
    "module": "ESNext",
    "moduleResolution": "bundler",
    "jsx": "react-jsx",
    "strict": true,
    "noUnusedLocals": true,
    "noUnusedParameters": true,
    "noFallthroughCasesInSwitch": true,
    "verbatimModuleSyntax": true,
    "skipLibCheck": true,
    "noEmit": true,
    "types": ["vite/client"]{plugins}
  }},
  "include": ["src", "vite.config.ts"]
}}
"#
    )
}

