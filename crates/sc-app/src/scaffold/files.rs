/// `node_modules` and `dist` only. The generated runtime is **not** ignored: it
/// is part of the source an admin reads and type-checks against, and a git repo
/// that omits it cannot be built anywhere but here.
const GITIGNORE: &str = "node_modules\ndist\n*.local\n";

/// The entry point. The auth provider wraps the router when there is one, so the
/// current user is known before any route renders.
fn main_tsx(auth: bool) -> String {
    let (import, open, close) = if auth {
        (
            "import { AuthProvider } from \"./auth\";\n",
            "    <AuthProvider>\n",
            "    </AuthProvider>\n",
        )
    } else {
        ("", "", "")
    };
    // The router's indentation follows the wrapper it is (or is not) inside.
    let pad = if auth { "  " } else { "" };
    format!(
        r#"import {{ StrictMode }} from "react";
import {{ createRoot }} from "react-dom/client";
import {{ BrowserRouter }} from "react-router-dom";
{import}import App from "./App";
import "./app.css";

const root = document.getElementById("root");
if (!root) throw new Error("no #root element in index.html");

createRoot(root).render(
  <StrictMode>
{open}{pad}    <BrowserRouter>
{pad}      <App />
{pad}    </BrowserRouter>
{close}  </StrictMode>,
);
"#
    )
}

/// The auth layer: a provider, a `useUser` hook and a gate.
///
/// It talks to the app's own `/api/login`, `/api/logout` and `/api/whoami`
/// through the generated client, so the session is a cookie the browser carries
/// and nothing here stores a credential. **This is a UI convenience, never the
/// enforcement point** (§2.1): every request is authorized again server-side, so
/// a route wrongly marked public renders a screen whose data calls fail, not a
/// leak.
const AUTH_TSX: &str = r#"import {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useState,
  type ReactNode,
} from "react";
import { api } from "./saltcorn/hooks";

export type User = { id: string; email: string; role: number };

export type AuthState = {
  /** The signed-in user, or null when anonymous. `undefined` while unknown. */
  user: User | null | undefined;
  signIn: (email: string, password: string) => Promise<void>;
  signOut: () => Promise<void>;
};

const AuthContext = createContext<AuthState | undefined>(undefined);

export function AuthProvider({ children }: { children: ReactNode }) {
  const [user, setUser] = useState<User | null | undefined>(undefined);

  useEffect(() => {
    let cancelled = false;
    // A 401 here is the ordinary anonymous case, not an error to report.
    api.whoami().then(
      (u) => !cancelled && setUser(u),
      () => !cancelled && setUser(null),
    );
    return () => {
      cancelled = true;
    };
  }, []);

  const signIn = useCallback(async (email: string, password: string) => {
    setUser(await api.login({ email, password }));
  }, []);

  const signOut = useCallback(async () => {
    await api.logout();
    setUser(null);
  }, []);

  return (
    <AuthContext.Provider value={{ user, signIn, signOut }}>
      {children}
    </AuthContext.Provider>
  );
}

export function useUser(): AuthState {
  const state = useContext(AuthContext);
  if (!state) throw new Error("useUser must be used inside <AuthProvider>");
  return state;
}
"#;

const LOGIN_TSX: &str = r#"import { useState, type FormEvent } from "react";
import { useUser } from "./auth";

export default function Login() {
  const { signIn } = useUser();
  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");
  const [error, setError] = useState<string | undefined>(undefined);
  const [busy, setBusy] = useState(false);

  const submit = async (e: FormEvent) => {
    e.preventDefault();
    setBusy(true);
    setError(undefined);
    try {
      await signIn(email, password);
    } catch (err) {
      setError(err instanceof Error ? err.message : String(err));
    } finally {
      setBusy(false);
    }
  };

  return (
    <form className="card sc-login" onSubmit={submit}>
      <h1>Sign in</h1>
      <label>
        Email
        <input
          type="email"
          value={email}
          autoComplete="username"
          onChange={(e) => setEmail(e.target.value)}
        />
      </label>
      <label>
        Password
        <input
          type="password"
          value={password}
          autoComplete="current-password"
          onChange={(e) => setPassword(e.target.value)}
        />
      </label>
      {error && <p className="sc-error">{error}</p>}
      <button type="submit" disabled={busy}>
        {busy ? "Signing in…" : "Sign in"}
      </button>
    </form>
  );
}
"#;

/// The shell: a header naming the app, a nav built from the route list, the
/// signed-in user, and the routes themselves.
///
/// Without auth there is no user to show and no gate to apply, so the header's
/// last cell and the route element's condition are simply not written. The
/// alternative — keeping them against a `user` that is always `null` — would
/// generate an app permanently displaying "not signed in" beside a sign-in button
/// that cannot exist.
fn app_tsx(project: &str, auth: bool) -> String {
    let (auth_imports, user_hook, user_cell, element) = if auth {
        (
            "import { useUser } from \"./auth\";\nimport Login from \"./Login\";\n",
            "  const { user, signOut } = useUser();\n",
            r#"        <span className="sc-user">
          {user ? (
            <>
              {user.email} <button onClick={() => void signOut()}>Sign out</button>
            </>
          ) : (
            "not signed in"
          )}
        </span>
"#,
            "r.public || user ? r.element : <Login />",
        )
    } else {
        ("", "", "", "r.element")
    };
    format!(
        r#"import {{ Link, Route, Routes, useLocation }} from "react-router-dom";
import {{ routes }} from "./routes";
{auth_imports}
export default function App() {{
{user_hook}  const location = useLocation();

  return (
    <div className="sc-app">
      <header className="sc-header">
        <strong>{project}</strong>
        <nav>
          {{routes
            .filter((r) => r.label)
            .map((r) => (
              <Link
                key={{r.path}}
                to={{r.path}}
                className={{location.pathname === r.path ? "active" : ""}}
              >
                {{r.label}}
              </Link>
            ))}}
        </nav>
{user_cell}      </header>
      <main>
        <Routes>
          {{routes.map((r) => (
            <Route key={{r.path}} path={{r.path}} element={{{element}}} />
          ))}}
        </Routes>
      </main>
    </div>
  );
}}
"#
    )
}

/// The route list, as data.
///
/// §2.1 chose this over a file-system convention: the scaffold knows the app's
/// tables, so it can write the list, and a list is inspectable and editable
/// without a build-time plugin scanning directories. `public` is the per-route
/// opt-out from the authenticated-by-default rule — one word, and its absence
/// means "signed in", which is the direction a forgotten flag should fail in.
///
/// An app with no auth has no login route to reach and no flag to carry: every
/// route is reachable, and a `public?: boolean` nothing reads would be a promise
/// about a gate that is not there.
fn routes_tsx(tables: &[&Table], auth: bool) -> String {
    let mut imports = String::from("import type { ReactNode } from \"react\";\n");
    if auth {
        imports.push_str("import Login from \"./Login\";\n");
    }
    let mut entries = String::new();
    for table in tables {
        let component = format!("{}Page", pascal(&table.name));
        imports.push_str(&format!(
            "import {component} from \"./pages/{}\";\n",
            pascal(&table.name)
        ));
        entries.push_str(&format!(
            "  {{ path: \"{}\", label: \"{}\", element: <{component} /> }},\n",
            route_path(&table.name, tables),
            title(&table.name)
        ));
    }
    let (public_field, login_route) = if auth {
        (
            "  /** Reachable without signing in. Absent means: sign-in required. */\n  public?: boolean;\n",
            "  { path: \"/login\", label: \"\", element: <Login />, public: true },\n",
        )
    } else {
        ("", "")
    };
    format!(
        r#"{imports}
export type AppRoute = {{
  /** The path within the app. */
  path: string;
  /** Shown in the nav; an empty label hides the route from it. */
  label: string;
  element: ReactNode;
{public_field}}};

export const routes: AppRoute[] = [
{entries}{login_route}];
"#
    )
}

/// The first table owns `/`; the rest get `/<table>`. An app whose only table is
/// `tasks` should not open on an empty index page.
fn route_path(table: &str, tables: &[&Table]) -> String {
    if tables.first().is_some_and(|t| t.name == table) {
        "/".to_owned()
    } else {
        format!("/{table}")
    }
}

/// One page per table: the list, a create form, and (when rows are addressable)
/// per-row edit and delete.
///
/// This is what "generate against the app's *actual* tables" buys — the app comes
/// up showing real rows in real columns, so the admin's first act is editing
/// working code rather than replacing a placeholder.
fn page_tsx(table: &Table, endpoints: &EndpointSet) -> String {
    let pascal = pascal(&table.name);
    let row_type = format!("{pascal}Row");
    // What the page may do is what the app's API offers, not what the table looks
    // like: a table the app declares but does not expose has no hooks to call.
    let can_create = has_op(endpoints, "create", &table.name);
    let can_delete = has_op(endpoints, "delete", &table.name);

    let headers = table
        .fields
        .iter()
        .map(|f| format!("            <th>{}</th>", f.base.label))
        .collect::<Vec<_>>()
        .join("\n");
    let cells = table
        .fields
        .iter()
        .map(|f| {
            format!(
                "              <td>{{String(row.{} ?? \"\")}}</td>",
                f.base.name
            )
        })
        .collect::<Vec<_>>()
        .join("\n");

    // Imports, hooks and state are assembled rather than templated, because a
    // page that imports a hook it does not call — or declares state it does not
    // use — fails the project's own type-check (`noUnusedLocals`), in generated
    // code the admin never wrote.
    let mut hook_imports = format!("use{pascal}");
    if can_create {
        hook_imports.push_str(&format!(", useCreate{pascal}"));
    }
    if can_delete {
        hook_imports.push_str(&format!(", useDelete{pascal}"));
    }

    let mut head = String::new();
    if can_create {
        head.push_str("import { useState } from \"react\";\n");
    }
    head.push_str(&format!(
        "import {{ {hook_imports}, type {row_type} }} from \"../saltcorn/hooks\";\n"
    ));

    let (empty_const, create_form) = if can_create {
        // Primary-key columns get no input. A v2 table's key is a
        // database-generated identity, so offering a control for it would invite
        // an insert that fights the database for the value — and the catalog does
        // not record "generated" as a property, so "is it the key?" is the honest
        // question available. A table with an admin-supplied key is the case this
        // gets wrong, and the fix is to edit the page, which is the admin's file.
        let inputs: Vec<&sc_catalog::DataField> =
            table.fields.iter().filter(|f| !f.primary_key).collect();
        let empty_form = inputs
            .iter()
            .map(|f| format!("  {}: {}", f.base.name, ts_empty(f)))
            .collect::<Vec<_>>()
            .join(",\n");
        let form_fields = inputs
            .iter()
            .map(|f| form_control(&f.base.name, basic_type(f)))
            .collect::<Vec<_>>()
            .join("\n");
        (
            format!("\nconst empty = {{\n{empty_form}\n}};\n"),
            format!(
                r#"      <form
        className="card"
        onSubmit={{(e) => {{
          e.preventDefault();
          void create.run(form).then(() => setForm(empty));
        }}}}
      >
{form_fields}
        <button type="submit" disabled={{create.pending}}>
          Add
        </button>
        {{create.error && <p className="sc-error">{{create.error.message}}</p>}}
      </form>
"#
            ),
        )
    } else {
        (String::new(), String::new())
    };

    let mut hooks = format!("  const {{ data, loading, error }} = use{pascal}();\n");
    if can_create {
        hooks.push_str(&format!("  const create = useCreate{pascal}();\n"));
        hooks.push_str("  const [form, setForm] = useState(empty);\n");
    }
    if can_delete {
        hooks.push_str(&format!("  const remove = useDelete{pascal}();\n"));
    }

    let (delete_column, delete_cell) = if can_delete {
        let pk = single_pk(table).unwrap_or_default();
        (
            "            <th />\n".to_owned(),
            format!(
                r#"              <td>
                <button onClick={{() => void remove.run(row.{pk})}}>Delete</button>
              </td>
"#
            ),
        )
    } else {
        (String::new(), String::new())
    };

    format!(
        r#"{head}{empty_const}
export default function {pascal}Page() {{
{hooks}
  if (error) return <p className="sc-error">{{error.message}}</p>;

  return (
    <section>
      <h1>{title}</h1>
{create_form}      {{loading && !data ? (
        <p>Loading…</p>
      ) : (
        <table>
          <thead>
            <tr>
{headers}
{delete_column}            </tr>
          </thead>
          <tbody>
            {{(data ?? []).map((row: {row_type}, i: number) => (
              <tr key={{i}}>
{cells}
{delete_cell}              </tr>
            ))}}
          </tbody>
        </table>
      )}}
    </section>
  );
}}
"#,
        title = title(&table.name)
    )
}

/// Whether the app's API exposes `op` on `table` — the single question every
/// "should this be generated?" decision here reduces to.
fn has_op(endpoints: &EndpointSet, op: &str, table: &str) -> bool {
    endpoints.find(&op_name(op, table)).is_some()
}

/// A labelled input bound into the create form's state, typed by the column.
