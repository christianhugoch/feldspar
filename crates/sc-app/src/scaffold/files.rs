/// The auth layer: a provider, a `useUser` hook and a gate.
///
/// It talks to the app's own `/api/login`, `/api/logout` and `/api/whoami`
/// through the generated client, so the session is a cookie the browser carries
/// and nothing here stores a credential. **This is a UI convenience, never the
/// enforcement point** (§2.1): every request is authorized again server-side, so
/// a route wrongly marked public renders a screen whose data calls fail, not a
/// leak.
const AUTH_TSX: &str = r#"import {
  createContext,
  useCallback,
  useContext,
  useEffect,
  useState,
  type ReactNode,
} from "react";
import { api } from "./feldspar/hooks";

export type User = { id: string; email: string; role: number };

export type AuthState = {
  /** The signed-in user, or null when anonymous. `undefined` while unknown. */
  user: User | null | undefined;
  signIn: (email: string, password: string) => Promise<void>;
  signOut: () => Promise<void>;
};

const AuthContext = createContext<AuthState | undefined>(undefined);

export function AuthProvider({ children }: { children: ReactNode }) {
  const [user, setUser] = useState<User | null | undefined>(undefined);

  useEffect(() => {
    let cancelled = false;
    // A 401 here is the ordinary anonymous case, not an error to report.
    api.whoami().then(
      (u) => !cancelled && setUser(u),
      () => !cancelled && setUser(null),
    );
    return () => {
      cancelled = true;
    };
  }, []);

  const signIn = useCallback(async (email: string, password: string) => {
    setUser(await api.login({ email, password }));
  }, []);

  const signOut = useCallback(async () => {
    await api.logout();
    setUser(null);
  }, []);

  return (
    <AuthContext.Provider value={{ user, signIn, signOut }}>
      {children}
    </AuthContext.Provider>
  );
}

export function useUser(): AuthState {
  const state = useContext(AuthContext);
  if (!state) throw new Error("useUser must be used inside <AuthProvider>");
  return state;
}
"#;

