//! The files a scaffolded React project is made of (TODO §2.3).
//!
//! Every function here is **pure**: table metadata and an endpoint set in, file
//! contents out. Nothing touches a file store, so the whole generator is
//! assertable in unit tests, and the store-writing half ([`super`]) has no
//! templates in it.
//!
//! Two kinds of file come out, and the difference is load-bearing (§2.1):
//!
//! - **Generated runtime** under `src/saltcorn/` — the typed client and the hooks
//!   over it, plus the GraphQL client and schema of an app that enables that
//!   provider. Rewritten on every build, so a table added later shows up in the
//!   types. Carries a "DO NOT EDIT" header because it means it.
//! - **The project itself** — `package.json`, the Vite/TS config, the app shell,
//!   the login screen, the routes and one page per table. Written **once**, at
//!   scaffold time, and never touched again. This is the admin's code from the
//!   moment it exists, which is why it is generated against their *actual*
//!   tables: a scaffold that comes up showing a placeholder counter is a
//!   template, while one that comes up showing their rows is a working app they
//!   can edit.
//!
//! The shell comes in two shapes, decided by [`has_auth`]: the authenticated one
//! §13.3 describes, and — for an application that exposes no auth endpoints — an
//! anonymous one with no auth layer at all.

use sc_api::{
    EndpointSet, GRAPHQL_CLIENT_FILE, GRAPHQL_SCHEMA_FILE, generate_client,
    generate_graphql_client, op_name,
};
use sc_catalog::Table;
use sc_types::BasicType;

use crate::api::AppGraphql;
use crate::react::{REACT_CLIENT_FILE, REACT_RUNTIME_SUBDIR};

/// A generated file: a path relative to the project directory, and its contents.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFile {
    /// Path relative to the project directory, `/`-separated (e.g. `src/App.tsx`).
    pub path: String,
    /// The file's contents.
    pub contents: String,
}

impl GeneratedFile {
    fn new(path: impl Into<String>, contents: impl Into<String>) -> GeneratedFile {
        GeneratedFile {
            path: path.into(),
            contents: contents.into(),
        }
    }
}

/// The header every regenerated file carries, so the boundary between "yours"
/// and "ours" is visible in the file rather than only in the documentation.
const GENERATED_HEADER: &str = "// Code generated by Saltcorn. DO NOT EDIT.\n\
                                // Rewritten on every build; edits here are lost.\n";

/// The header a generated **GraphQL schema** carries. The same sentence as
/// [`GENERATED_HEADER`] in the comment syntax SDL actually has: `//` is not a
/// comment in GraphQL, and a header that made the schema unparseable would
/// break the one tool the file exists for.
const GENERATED_SDL_HEADER: &str = "# Schema generated by Saltcorn. DO NOT EDIT.\n\
                                    # Rewritten on every build; edits here are lost.\n\n";

/// The files under `src/saltcorn/`: the typed client, the typed hooks, and —
/// for an app that enables the GraphQL provider — its client and its schema.
///
/// Emitted by the scaffold *and* by every subsequent build, which is what keeps
/// them honest when the app's tables change. The schema is written **only** for
/// an app that enables the provider: an app without one has no GraphQL contract,
/// and a `schema.graphql` sitting in its tree describing an API it does not
/// serve would be a lie its editor believed.
pub fn runtime_files(
    tables: &[Table],
    endpoints: &EndpointSet,
    graphql: Option<&AppGraphql>,
) -> Vec<GeneratedFile> {
    let mut files = vec![
        GeneratedFile::new(
            format!("{REACT_RUNTIME_SUBDIR}/{REACT_CLIENT_FILE}"),
            generate_client(endpoints),
        ),
        GeneratedFile::new(
            format!("{REACT_RUNTIME_SUBDIR}/hooks.ts"),
            hooks_ts(tables, endpoints),
        ),
    ];
    if let Some(graphql) = graphql {
        files.push(GeneratedFile::new(
            format!("{REACT_RUNTIME_SUBDIR}/{GRAPHQL_CLIENT_FILE}"),
            generate_graphql_client(&graphql.mount),
        ));
        files.push(GeneratedFile::new(
            format!("{REACT_RUNTIME_SUBDIR}/{GRAPHQL_SCHEMA_FILE}"),
            format!("{GENERATED_SDL_HEADER}{}", graphql.sdl),
        ));
    }
    files
}

/// The tables the generated project may have pages and hooks for: those the
/// app's API actually exposes.
///
/// **The endpoint set is the source of truth, not the table list**, and the
/// difference is not academic. An application declares tables *and* API
/// providers; a table it declares but does not expose has no `listTasks` on the
/// generated client, so a page calling one would not compile — which is exactly
/// what a real app hit. Deriving "what can this project talk to?" from the same
/// value the client is generated from makes that class of mismatch unable to
/// occur, where re-deriving it from the tables only made the two agree *by
/// coincidence* while they happened to be computed the same way.
fn exposed_tables<'a>(tables: &'a [Table], endpoints: &EndpointSet) -> Vec<&'a Table> {
    tables
        .iter()
        .filter(|t| endpoints.find(&op_name("list", &t.name)).is_some())
        .collect()
}

/// Whether this application can sign anyone in.
///
/// The scaffold's auth layer is generated code calling `login` / `logout` /
/// `whoami` through the typed client, so it can only exist when the application
/// exposes them — which today means the REST provider (§13.4). An app that does
/// not gets the anonymous shell instead of a login screen whose three calls do
/// not compile: **authenticated by default** (§13.3) is a statement about a
/// scaffold's *routes*, and it cannot lock a door that has no key.
///
/// All three or none: a partial set is a provider having changed under us, and
/// generating half an auth layer against it is how you get the error this branch
/// exists to prevent.
pub fn has_auth(endpoints: &EndpointSet) -> bool {
    sc_api::AUTH_ENDPOINTS
        .iter()
        .all(|name| endpoints.find(name).is_some())
}

/// The whole project: the runtime plus everything written once.
pub fn project_files(
    project: &str,
    tables: &[Table],
    endpoints: &EndpointSet,
    graphql: Option<&AppGraphql>,
) -> Vec<GeneratedFile> {
    let exposed = exposed_tables(tables, endpoints);
    let auth = has_auth(endpoints);
    let mut files = vec![
        GeneratedFile::new("package.json", package_json(project)),
        GeneratedFile::new("vite.config.ts", VITE_CONFIG),
        GeneratedFile::new("tsconfig.json", tsconfig(graphql.is_some())),
        GeneratedFile::new("index.html", index_html(project)),
        GeneratedFile::new(".gitignore", GITIGNORE),
        GeneratedFile::new("src/main.tsx", main_tsx(auth)),
        GeneratedFile::new("src/App.tsx", app_tsx(project, auth)),
        GeneratedFile::new("src/routes.tsx", routes_tsx(&exposed, auth)),
        GeneratedFile::new("src/app.css", APP_CSS),
    ];
    if auth {
        files.push(GeneratedFile::new("src/auth.tsx", AUTH_TSX));
        files.push(GeneratedFile::new("src/Login.tsx", LOGIN_TSX));
    }
    for table in &exposed {
        files.push(GeneratedFile::new(
            format!("src/pages/{}.tsx", pascal(&table.name)),
            page_tsx(table, endpoints),
        ));
    }
    files.extend(runtime_files(tables, endpoints, graphql));
    files
}

