/// The provider's registered name.
pub const REST_PROVIDER: &str = "rest";

/// Which table operation an endpoint runs. Recorded per endpoint at projection
/// time so dispatch is a lookup rather than a re-parse of the path.
#[derive(Debug, Clone, PartialEq, Eq)]
enum RestOp {
    /// `GET /{table}` — every row.
    List,
    /// `POST /{table}` — insert a row.
    Create,
    /// `PUT /{table}/{id}` — update the row with that primary key.
    Update,
    /// `DELETE /{table}/{id}` — delete the row with that primary key.
    Delete,
    /// `GET /{table}/{id}/{field}` — serve the bytes behind the row's `File`
    /// field (§4).
    Download {
        /// The `File` field whose stored path is resolved and served.
        field: String,
    },
    /// `POST /{table}/{id}/{field}/{filename}` — store the raw request body in
    /// the field's store and folder and point the row's field at it (§4).
    Upload {
        /// The `File` field the upload lands in.
        field: String,
    },
}

/// A projected table endpoint: the operation and the table it runs against.
#[derive(Debug, Clone)]
struct TableRoute {
    op: RestOp,
    table: String,
}

/// The path segment an app's exposed triggers live under: `POST
/// {mount}/actions/{name}`.
///
/// A literal segment rather than the trigger name at the mount's root, so a
/// trigger can never collide with a table (`/api/posts` is the `posts` table
/// whatever anyone calls a trigger) and a reader of a URL can tell which of the
/// two they are looking at.
const ACTIONS_SEGMENT: &str = "actions";

/// The endpoint names of the app's own auth operations. They are fixed rather
/// than derived from a table, so a table cannot collide with them: `op_name`
/// always prefixes a table's operations with `list`/`create`/`update`/`delete`.
const LOGIN: &str = "login";
const LOGOUT: &str = "logout";
const WHOAMI: &str = "whoami";

/// A REST projection of an application's endpoint set (design §13.4).
pub struct RestProvider {
    mount: String,
    endpoints: EndpointSet,
    /// Endpoint name → the table operation it runs. Custom routes are absent
    /// here; they resolve through their [`HandlerRef`] instead.
    routes: HashMap<String, TableRoute>,
    /// Endpoint name → the trigger it runs, for the app's exposed subset.
    trigger_routes: HashMap<String, String>,
    /// The dispatcher an exposed trigger is run through. Injected by the server
    /// via [`with_dispatcher`](RestProvider::with_dispatcher); absent in the
    /// contexts that only need the endpoint *shapes* (client generation), where
    /// calling one is a configuration error rather than a silent no-op.
    dispatcher: Option<Arc<sc_action::TriggerDispatcher>>,
    /// The engine behind ownership formulas' reified path (§7.3). Injected by
    /// the server via [`with_evaluator`](RestProvider::with_evaluator); when
    /// absent, a formula that needs it **fails closed** with a configuration
    /// error rather than granting anything.
    evaluator: Option<Arc<dyn JsEvaluator>>,
}

impl RestProvider {
    /// Project `tables` into a REST API mounted at `mount`.
    ///
    /// The tables are the application's declared subset, already resolved
    /// against the catalog by the caller — an app only ever exposes the tables it
    /// declares (§13.2), and this crate sits below `sc-app` so it takes the
    /// resolved tables rather than the `Application`.
    ///
    /// Each table contributes four endpoints, each carrying the auth requirement
    /// its own access rules dictate. A table with no single-column primary key
    /// gets only the collection endpoints (list/create): there is no way to
    /// address one of its rows, so `PUT`/`DELETE` would be undeliverable
    /// promises.
    pub fn project(mount: impl Into<String>, tables: &[Table]) -> RestProvider {
        RestProvider::project_with(mount, tables, &[])
    }

    /// [`project`](RestProvider::project) plus one endpoint per exposed trigger
    /// (§10.2).
    ///
    /// The triggers are the application's declared subset, already resolved
    /// against the live trigger set by the caller — the same arrangement the
    /// tables have, and for the same reason: this crate sits below `sc-app`, so
    /// it takes what an app resolved rather than the `Application`.
    pub fn project_with(
        mount: impl Into<String>,
        tables: &[Table],
        triggers: &[sc_action::Trigger],
    ) -> RestProvider {
        let mount = normalize_mount(&mount.into());
        let mut endpoints = EndpointSet::new();
        let mut routes = HashMap::new();
        let mut trigger_routes = HashMap::new();

        // The app's own auth (§7.2). Projected for every app: an app whose users
        // cannot log in can only ever serve public-role data, and a caller has to
        // have some way to stop being anonymous. Public-role browsing still works
        // without ever calling these.
        endpoints.register(
            Endpoint::new(LOGIN, Method::Post, path_at(&mount).lit("login"))
                .input(credentials_schema())
                .output(user_summary_schema())
                // The only public endpoint: it is what turns an anonymous caller
                // into an authenticated one.
                .auth(AuthRequirement::Public),
        );
        endpoints.register(
            Endpoint::new(LOGOUT, Method::Post, path_at(&mount).lit("logout"))
                .auth(AuthRequirement::LoggedIn),
        );
        endpoints.register(
            Endpoint::new(WHOAMI, Method::Get, path_at(&mount).lit("whoami"))
                .output(user_summary_schema())
                .auth(AuthRequirement::LoggedIn),
        );

        for table in tables {
            let name = &table.name;
            // A table with an ownership formula relaxes its endpoints to
            // Public (§7.3): the formula decides `user === null` — an admin
            // may grant anonymous callers rows — so the gate moves from the
            // endpoint's auth into the handler, where the rule becomes
            // "meets the role floor OR the formula grants the row". A table
            // without a formula keeps the MinRole gate exactly as before.
            let (read, write) = if table.ownership.is_some() {
                (AuthRequirement::Public, AuthRequirement::Public)
            } else {
                (
                    AuthRequirement::MinRole(table.access.min_role_read),
                    AuthRequirement::MinRole(table.access.min_role_write),
                )
            };
            let collection = || path_at(&mount).lit(name);

            let mut add = |op: RestOp, ep: Endpoint| {
                routes.insert(
                    ep.name.clone(),
                    TableRoute {
                        op,
                        table: name.clone(),
                    },
                );
                endpoints.register(ep);
            };

            add(
                RestOp::List,
                Endpoint::new(op_name("list", name), Method::Get, collection())
                    .output(TypeSchema::array(TypeSchema::json()))
                    .auth(read.clone())
                    .handler(HandlerRef::named(op_name("list", name))),
            );
            add(
                RestOp::Create,
                Endpoint::new(op_name("create", name), Method::Post, collection())
                    .input(TypeSchema::json())
                    .output(TypeSchema::json())
                    .auth(write.clone())
                    .handler(HandlerRef::named(op_name("create", name))),
            );

            // Row-addressing endpoints need exactly one primary-key column to
            // address by; `single_pk` is the same rule the row layer enforces.
            let Ok(pk) = rows::single_pk(table) else {
                continue;
            };
            let id_ty = table
                .field(&pk)
                .and_then(|f| f.base.type_.as_basic())
                .map_or(ValueType::Text, ValueType::from_basic);
            let item = || path_at(&mount).lit(name).param("id", id_ty);

            add(
                RestOp::Update,
                Endpoint::new(op_name("update", name), Method::Put, item())
                    .input(TypeSchema::json())
                    .output(TypeSchema::json())
                    .auth(write.clone())
                    .handler(HandlerRef::named(op_name("update", name))),
            );
            add(
                RestOp::Delete,
                Endpoint::new(op_name("delete", name), Method::Delete, item())
                    .output(TypeSchema::json())
                    .auth(write.clone())
                    .handler(HandlerRef::named(op_name("delete", name))),
            );

            // A `File` field's bytes (§4), addressed **by table, row id and
            // field name** — never by raw store path. The row is what the caller
            // is allowed to see, and letting an app name an arbitrary path would
            // make the field's folder restriction advisory. Reads carry the
            // table's read rule, uploads its write rule; the file's own
            // path-cumulative `min_role` is enforced on top at request time, so
            // the stricter of the two always decides.
            for data_field in &table.fields {
                if !matches!(data_field.kind, DataFieldKind::File { .. }) {
                    continue;
                }
                let field = &data_field.base.name;
                let scoped = format!("{name}_{field}");
                let file_item = || path_at(&mount).lit(name).param("id", id_ty).lit(field);
                add(
                    RestOp::Download {
                        field: field.clone(),
                    },
                    Endpoint::new(op_name("download", &scoped), Method::Get, file_item())
                        .binary_output()
                        .auth(read.clone())
                        .handler(HandlerRef::named(op_name("download", &scoped))),
                );
                add(
                    RestOp::Upload {
                        field: field.clone(),
                    },
                    Endpoint::new(
                        op_name("upload", &scoped),
                        Method::Post,
                        // The filename is a path parameter, so it is one
                        // segment by construction — a nested or traversing
                        // destination cannot even be expressed in the URL.
                        file_item().param("filename", ValueType::Text),
                    )
                    .binary_input()
                    .output(TypeSchema::json())
                    .auth(write.clone())
                    .handler(HandlerRef::named(op_name("upload", &scoped))),
                );
            }
        }

        // The app's exposed triggers, one `POST {mount}/actions/{name}` each.
        // The role floor is the trigger's own, and an unset one is **admin**:
        // `min_role` is optional on a trigger because most triggers are never
        // called from outside at all, so its absence means "nobody has decided",
        // which must not read as "everybody".
        for trigger in triggers {
            let name = op_name("run", &trigger.name);
            trigger_routes.insert(name.clone(), trigger.name.clone());
            endpoints.register(
                Endpoint::new(
                    name.clone(),
                    Method::Post,
                    path_at(&mount).lit(ACTIONS_SEGMENT).lit(&trigger.name),
                )
                // The posted body *is* the event's payload, whatever shape the
                // action's configuration reads out of it, so it is typed as
                // json rather than as a struct nobody could derive.
                .input(TypeSchema::json())
                .output(TypeSchema::json())
                .auth(AuthRequirement::MinRole(
                    trigger.min_role.unwrap_or(sc_auth::ROLE_ADMIN),
                ))
                .handler(HandlerRef::named(name)),
            );
        }

        RestProvider {
            mount,
            endpoints,
            routes,
            trigger_routes,
            dispatcher: None,
            evaluator: None,
        }
    }

    /// Inject the JavaScript evaluator ownership formulas' reified path runs
    /// on. The server constructs one engine and shares it across every
    /// provider; a provider without one still enforces translatable formulas
    /// symbolically and fails closed on the rest.
    pub fn with_evaluator(mut self, evaluator: Arc<dyn JsEvaluator>) -> RestProvider {
        self.evaluator = Some(evaluator);
        self
    }

    /// Inject the trigger dispatcher an exposed trigger's endpoint runs through
    /// — the *same* dispatcher every other event fires on, so a trigger called
    /// over an app's API is the trigger the admin configured, with the same
    /// `only_if`, the same cascade bound and the same action.
    pub fn with_dispatcher(
        mut self,
        dispatcher: Arc<sc_action::TriggerDispatcher>,
    ) -> RestProvider {
        self.dispatcher = Some(dispatcher);
        self
    }

    /// Run one of the app's exposed triggers, with the request body as the
    /// event's payload and the caller travelling with it (§10.2).
    ///
    /// The caller is not merely recorded: it is what the trigger's action sees as
    /// `user`, and what a row the action writes reports as the cause of its own
    /// event. A failing action comes back as an **error** — somebody asked for
    /// this one, so somebody is waiting for the answer — which is the same
    /// contract the admin's "run this now" button has.
    async fn run_trigger(
        &self,
        trigger: &str,
        req: &ApiRequest,
        cat: &Catalog,
        user: Option<&User>,
    ) -> Result<ApiResponse> {
        let dispatcher = self.dispatcher.as_ref().ok_or_else(|| {
            Error::config(format!(
                "this application exposes trigger `{trigger}` but no trigger \
                 dispatcher is available in this context, so it cannot be run"
            ))
        })?;
        let caller = ownership::caller_context(user);
        let result = dispatcher
            .run_trigger(cat, trigger, req.body.clone(), Some(&caller))
            .await?;
        Ok(ApiResponse::ok(result))
    }

    /// Add a developer-authored custom route (guest code or SQL, §13.4).
    ///
    /// The endpoint is projected and typed like any other, but running it is
    /// stubbed for the MVP: [`handle`](RestProvider::handle) answers `501 Not
    /// Implemented` for a [`HandlerRef::GuestCode`]/[`HandlerRef::Sql`] handler.
    pub fn with_custom_route(mut self, endpoint: Endpoint) -> RestProvider {
        self.endpoints.register(endpoint);
        self
    }

    /// Find the endpoint matching `req`, with its captured path parameters.
    ///
    /// `Err` distinguishes the two ways a request can miss: a path no endpoint
    /// claims (`404`) versus a path that exists but not for this method (`405`).
    // `clippy::result_large_err` does not apply: the `Err` here is not an error
    // being propagated up a call stack, it *is* the response to send — the one
    // caller either dispatches the endpoint or returns this `ApiResponse`
    // unchanged. Boxing it would add an indirection at seven call sites to shrink
    // a value that is constructed once per missed request and immediately
    // returned. (`ApiResponse` already boxes the one field worth boxing, `raw`.)
    #[allow(clippy::result_large_err)]
    fn resolve(&self, req: &ApiRequest) -> std::result::Result<(&Endpoint, Params), ApiResponse> {
        let mut path_matched = false;
        for ep in self.endpoints.iter() {
            match ep.path.match_path(&req.path) {
                Some(params) if ep.method == req.method => return Ok((ep, params)),
                Some(_) => path_matched = true,
                None => {}
            }
        }
        Err(if path_matched {
            ApiResponse::error(
                405,
                format!("{} is not allowed on {}", req.method.as_str(), req.path),
            )
        } else {
            ApiResponse::error(404, format!("no endpoint for {}", req.path))
        })
    }

    /// Verify credentials against `sc-auth` and start a session.
    ///
    /// Uses the same `authenticate` the admin login does, but for **any** role —
    /// an app's users are not admins. A bad password and an unknown user are the
    /// same `401` with the same message: distinguishing them would tell an
    /// attacker which emails are registered.
    async fn login(&self, body: &Json, cat: &Catalog) -> Result<ApiResponse> {
        let (email, password) = credentials(body)?;
        match authenticate(cat, &email, &password).await? {
            Some(user) => {
                let summary = user_summary_json(&user);
                Ok(ApiResponse::start_session(user, summary))
            }
            None => Ok(ApiResponse::error(401, "invalid credentials")),
        }
    }

    /// Run a resolved table operation, enforcing the §7.3 access rule:
    /// **meets the operation's role floor OR the ownership formula grants the
    /// row**. Callers at or above the floor take exactly the pre-formula
    /// paths; everyone else exists only where the formula says so — and a row
    /// the formula withholds answers with the *same* not-found a missing row
    /// gets, so nothing about the table's contents can be probed.
    async fn run(
        &self,
        route: &TableRoute,
        params: &Params,
        req: &ApiRequest,
        cat: &Catalog,
        user: Option<&User>,
    ) -> Result<ApiResponse> {
        let table = cat.require(&route.table)?;
        let body = &req.body;
        let id = || -> Result<&str> {
            params
                .get("id")
                .map(String::as_str)
                .ok_or_else(|| Error::invalid("missing path parameter `id`"))
        };
        // When the database enforces this table's ownership (§6), the runtime
        // checks below are switched off entirely: every row operation runs in a
        // caller-context transaction and the generated policies decide. "You no
        // longer have to check" (GOALS), and joinfields are not refetched — the
        // policies' correlated subselects do that in the database.
        if table.rls_enabled {
            return self.run_rls(route, &table, params, req, cat, user).await;
        }
        // The caller's role for the path-cumulative file rule. Anonymous is
        // public; the table-level gate (floor or formula) runs separately.
        let role = user.map_or(ROLE_PUBLIC, |u| u.role);
        let meets_read = ownership::meets(user, table.access.min_role_read);
        let meets_write = ownership::meets(user, table.access.min_role_write);
        // The formula, for callers below the floor. Its absence there means
        // the endpoint was Public only by a stale projection — deny exactly as
        // the MinRole gate would have.
        // `Err(())` is "deny as the MinRole gate would" — the response is built
        // at the call site to keep this closure's error small.
        let formula = |allowed: bool| -> std::result::Result<Option<&sc_expr::Formula>, ()> {
            if allowed {
                Ok(None)
            } else {
                match &table.ownership {
                    Some(f) => Ok(Some(f)),
                    None => Err(()),
                }
            }
        };
        let evaluator = self.evaluator.as_ref();
        // The caller, travelling with every write so the event it raises knows
        // who caused it (§10.2). On this path it sets no GUCs — the table is not
        // RLS-enforced, and `rows` routes by the table, not by the context's
        // presence — it is identity, not authority.
        let caller = ownership::caller_context(user);

        Ok(match &route.op {
            RestOp::List => match formula(meets_read) {
                Err(()) => forbidden(user),
                Ok(None) => ApiResponse::ok(rows::list_rows(cat, &table).await?),
                Ok(Some(f)) => ApiResponse::ok(
                    ownership::list_owned_rows(cat, &table, f, user, evaluator).await?,
                ),
            },
            RestOp::Create => {
                match formula(meets_write) {
                    Err(()) => return Ok(forbidden(user)),
                    Ok(None) => {}
                    // An insert is checked against the proposed row, `_insert`
                    // folded true (§7.3) — WITH CHECK semantics at runtime.
                    Ok(Some(f)) => {
                        let proposed = rows::coerce_row_values(&table, body)?;
                        if !ownership::row_allowed(
                            cat,
                            &table,
                            f,
                            Operation::Insert,
                            user,
                            evaluator,
                            &proposed,
                        )
                        .await?
                        {
                            return Ok(ApiResponse::error(
                                403,
                                "this row is outside your ownership",
                            ));
                        }
                    }
                }
                ApiResponse::with_status(
                    201,
                    rows::create_row_ctx(cat, &table, body, Some(&caller)).await?,
                )
            }
            RestOp::Update => {
                let id = id()?;
                match formula(meets_write) {
                    Err(()) => return Ok(forbidden(user)),
                    Ok(None) => ApiResponse::ok(
                        rows::update_row_ctx(cat, &table, id, body, Some(&caller)).await?,
                    ),
                    Ok(Some(f)) => {
                        // USING: granted on the existing row…
                        let existing = self
                            .owned_row(cat, &table, f, Operation::Update, user, id)
                            .await?;
                        // …and WITH CHECK: granted on the proposed row too, so
                        // an update cannot move the row out of the caller's
                        // ownership.
                        let changes = rows::coerce_row_values(&table, body)?;
                        let merged = ownership::merged_row(&table, &existing, &changes);
                        if !ownership::row_allowed(
                            cat,
                            &table,
                            f,
                            Operation::Update,
                            user,
                            evaluator,
                            &merged,
                        )
                        .await?
                        {
                            return Ok(ApiResponse::error(
                                403,
                                "the update would move this row out of your ownership",
                            ));
                        }
                        // The translated predicate rides in the UPDATE's WHERE
                        // when it can, closing the check-to-write race.
                        let guard =
                            ownership::write_guard(cat, &table, f, Operation::Update, user)?;
                        ApiResponse::ok(
                            rows::update_row_guarded(cat, &table, id, body, guard, Some(&caller))
                                .await?,
                        )
                    }
                }
            }
            RestOp::Delete => {
                let id = id()?;
                match formula(meets_write) {
                    Err(()) => return Ok(forbidden(user)),
                    Ok(None) => {
                        ApiResponse::ok(rows::delete_row_ctx(cat, &table, id, Some(&caller)).await?)
                    }
                    Ok(Some(f)) => {
                        self.owned_row(cat, &table, f, Operation::Delete, user, id)
                            .await?;
                        let guard =
                            ownership::write_guard(cat, &table, f, Operation::Delete, user)?;
                        ApiResponse::ok(
                            rows::delete_row_guarded(cat, &table, id, guard, Some(&caller)).await?,
                        )
                    }
                }
            }
            RestOp::Download { field } => {
                match formula(meets_read) {
                    Err(()) => return Ok(forbidden(user)),
                    Ok(None) => {}
                    // A file read is a read of the row (§7.3); the file's own
                    // path-cumulative rule still runs inside `download`.
                    Ok(Some(f)) => {
                        self.owned_row(cat, &table, f, Operation::Read, user, id()?)
                            .await?;
                    }
                }
                download(cat, &table, field, id()?, role).await?
            }
            RestOp::Upload { field } => {
                let filename = params
                    .get("filename")
                    .map(String::as_str)
                    .ok_or_else(|| Error::invalid("missing path parameter `filename`"))?;
                match formula(meets_write) {
                    Err(()) => return Ok(forbidden(user)),
                    Ok(None) => {}
                    // An upload updates the row's field: granted on the
                    // existing row, and on the row as it will be — the formula
                    // may read the very field being written.
                    Ok(Some(f)) => {
                        let id = id()?;
                        let existing = self
                            .owned_row(cat, &table, f, Operation::Update, user, id)
                            .await?;
                        let (_, folder, _) = file_field(&table, field)?;
                        let path = upload_path(folder, filename);
                        let mut changes = std::collections::BTreeMap::new();
                        changes.insert(field.clone(), Value::Text(path));
                        let merged = ownership::merged_row(&table, &existing, &changes);
                        if !ownership::row_allowed(
                            cat,
                            &table,
                            f,
                            Operation::Update,
                            user,
                            evaluator,
                            &merged,
                        )
                        .await?
                        {
                            return Ok(ApiResponse::error(
                                403,
                                "the upload would move this row out of your ownership",
                            ));
                        }
                    }
                }
                upload_ctx(
                    cat,
                    &table,
                    field,
                    id()?,
                    filename,
                    req.raw.clone(),
                    role,
                    &caller,
                )
                .await?
            }
        })
    }

    /// The existing row `id`, granted to the caller by the formula for `op` —
    /// or the **same not-found a missing row gets**, which is what makes
    /// denial indistinguishable from absence.
    async fn owned_row(
        &self,
        cat: &Catalog,
        table: &Table,
        formula: &sc_expr::Formula,
        op: Operation,
        user: Option<&User>,
        id: &str,
    ) -> Result<std::collections::BTreeMap<String, Value>> {
        let not_found = || {
            let pk = rows::single_pk(table)?;
            Err(Error::not_found(format!("no row with {pk} = {id}")))
        };
        let Some(existing) = ownership::fetch_row_values(cat, table, formula, id).await? else {
            return not_found();
        };
        if !ownership::row_allowed(
            cat,
            table,
            formula,
            op,
            user,
            self.evaluator.as_ref(),
            &existing,
        )
        .await?
        {
            return not_found();
        }
        Ok(existing)
    }

    /// Run a row operation on an **RLS-enabled** table (§6): the database's
    /// policies do all the gating, so there is no formula translation, no
    /// evaluator, and no fetch-then-check here. Every statement runs through a
    /// caller-context transaction, and a policy that withholds a row surfaces
    /// as the same not-found an absent row gets (`run_in_context` maps `42501`).
    /// The file endpoints still layer the path-cumulative file rule on top.
    async fn run_rls(
        &self,
        route: &TableRoute,
        table: &Table,
        params: &Params,
        req: &ApiRequest,
        cat: &Catalog,
        user: Option<&User>,
    ) -> Result<ApiResponse> {
        let ctx = ownership::caller_context(user);
        let body = &req.body;
        let role = user.map_or(ROLE_PUBLIC, |u| u.role);
        let id = || -> Result<&str> {
            params
                .get("id")
                .map(String::as_str)
                .ok_or_else(|| Error::invalid("missing path parameter `id`"))
        };
        Ok(match &route.op {
            RestOp::List => {
                ApiResponse::ok(rows::list_rows_where(cat, table, None, Some(&ctx)).await?)
            }
            RestOp::Create => ApiResponse::with_status(
                201,
                rows::create_row_ctx(cat, table, body, Some(&ctx)).await?,
            ),
            RestOp::Update => ApiResponse::ok(
                rows::update_row_guarded(cat, table, id()?, body, None, Some(&ctx)).await?,
            ),
            RestOp::Delete => ApiResponse::ok(
                rows::delete_row_guarded(cat, table, id()?, None, Some(&ctx)).await?,
            ),
            RestOp::Download { field } => {
                download_ctx(cat, table, field, id()?, role, &ctx).await?
            }
            RestOp::Upload { field } => {
                let filename = params
                    .get("filename")
                    .map(String::as_str)
                    .ok_or_else(|| Error::invalid("missing path parameter `filename`"))?;
                upload_ctx(
                    cat,
                    table,
                    field,
                    id()?,
                    filename,
                    req.raw.clone(),
                    role,
                    &ctx,
                )
                .await?
            }
        })
    }
}

/// The rejection a caller below the floor gets when no formula extends access:
/// exactly what the `MinRole` gate answers, per caller state.
fn forbidden(user: Option<&User>) -> ApiResponse {
    match user {
        None => ApiResponse::error(401, "authentication required"),
        Some(_) => ApiResponse::error(403, "insufficient privilege"),
    }
}

/// The store-relative path an upload of `filename` lands at — the same shape
/// `upload` itself builds, factored so the ownership pre-check sees the row
/// exactly as it will be written.
fn upload_path(folder: Option<&str>, filename: &str) -> String {
    match folder
        .map(|f| f.trim_matches('/'))
        .filter(|f| !f.is_empty())
    {
        Some(folder) => format!("{folder}/{filename}"),
        None => filename.to_owned(),
    }
}

/// Serve the bytes behind a row's `File` field (§4).
///
/// The table's `min_role_read` was enforced as the endpoint's auth before this
/// ran; here the file's own **path-cumulative** `min_role` (§14.1) is enforced
/// on top — the stricter of the two decides, never the looser, because both
/// checks must pass. The projection only routes file endpoints for `File`
/// fields, but the catalog may have changed under a mounted app, so the current
/// field is re-checked rather than trusted.
async fn download(
    cat: &Catalog,
    table: &Table,
    field: &str,
    id: &str,
    role: u8,
) -> Result<ApiResponse> {
    download_inner(cat, table, field, id, role, None).await
}

/// [`download`] resolving the row's file path through an RLS caller context
/// (§6), so a file behind a row the policies withhold is a not-found.
async fn download_ctx(
    cat: &Catalog,
    table: &Table,
    field: &str,
    id: &str,
    role: u8,
    context: &CallerContext,
) -> Result<ApiResponse> {
    download_inner(cat, table, field, id, role, Some(context)).await
}

async fn download_inner(
    cat: &Catalog,
    table: &Table,
    field: &str,
    id: &str,
    role: u8,
    context: Option<&CallerContext>,
) -> Result<ApiResponse> {
    let (store_name, _, _) = file_field(table, field)?;
    let path = match rows::read_field_ctx(cat, table, field, id, context).await? {
        Value::Text(path) if !path.is_empty() => path,
        // The row exists but references nothing: for the caller that is "no
        // file here", the same not-found an empty shelf gets.
        _ => {
            return Err(Error::not_found(format!(
                "row {id} has no file in `{field}`"
            )));
        }
    };
    let store = cat.require_file_store(store_name)?;
    let floor = store_floor(cat, store_name).await?;
    check_access(store.as_ref(), floor, &path, role).await?;
    let bytes = store.read(&path).await?;
    // Content type by extension, exactly as the field's MIME allow-list is
    // enforced — the two must agree on what a path is.
    let content_type =
        mime_for_path(&path).unwrap_or_else(|| "application/octet-stream".to_owned());
    Ok(ApiResponse::file(bytes, content_type))
}

/// Store an upload's bytes behind a row's `File` field (§4).
///
/// The table's `min_role_write` was enforced as the endpoint's auth. The bytes
/// land in the **field's** store and folder — the caller names only a filename,
/// one path segment by route construction — and the field's MIME restrictions
/// are applied here, server-side: a client-side accept filter is a convenience,
/// not a control. The row is updated to reference the stored path, through the
/// same `update_row` any JSON write takes (so the field's rules are enforced
/// twice, harmlessly).
///
/// The caller travels with it: on an RLS table it is the authority the
/// pre-existence check and the field update both run under, so a caller cannot
/// upload into a row they may not write; on any table it is who the update event
/// reports as its cause.
#[allow(clippy::too_many_arguments)]
async fn upload_ctx(
    cat: &Catalog,
    table: &Table,
    field: &str,
    id: &str,
    filename: &str,
    data: Option<bytes::Bytes>,
    role: u8,
    context: &CallerContext,
) -> Result<ApiResponse> {
    upload_inner(cat, table, field, id, filename, data, role, Some(context)).await
}

#[allow(clippy::too_many_arguments)]
async fn upload_inner(
    cat: &Catalog,
    table: &Table,
    field: &str,
    id: &str,
    filename: &str,
    data: Option<bytes::Bytes>,
    role: u8,
    context: Option<&CallerContext>,
) -> Result<ApiResponse> {
    let (store_name, folder, mime_allow) = file_field(table, field)?;
    let Some(data) = data else {
        return Err(Error::invalid(
            "expected the request body to be the file's bytes, sent with its own \
             content type (not application/json)",
        ));
    };

    let path = upload_path(folder, filename);
    validate_file_path(&path, folder, mime_allow).map_err(|e| rows::field_error(field, e))?;

    let store = cat.require_file_store(store_name)?;
    let floor = store_floor(cat, store_name).await?;
    // Writing into a restricted place is as governed as reading from one.
    check_access(store.as_ref(), floor, &path, role).await?;

    // The row must exist (and be writable by the caller) before the bytes land:
    // failing afterwards would leave an orphaned file no row references.
    rows::read_field_ctx(cat, table, field, id, context).await?;
    store.write(&path, data).await?;
    let updated =
        rows::update_row_guarded(cat, table, id, &json!({ field: path }), None, context).await?;
    Ok(ApiResponse::with_status(201, updated))
}

/// The `File` kind parameters of `field` on `table`: its store name, folder and
/// MIME allow-list. A field that is not (or is no longer) a `File` is a
/// not-found — the endpoint's own existence is what claimed otherwise.
fn file_field<'t>(
    table: &'t Table,
    field: &str,
) -> Result<(&'t str, Option<&'t str>, &'t [String])> {
    let found = table
        .field(field)
        .ok_or_else(|| Error::not_found(format!("`{}` has no field `{field}`", table.name)))?;
    match &found.kind {
        DataFieldKind::File {
            store,
            folder,
            mime_allow,
        } => Ok((store.0.as_str(), folder.as_deref(), mime_allow.as_slice())),
        _ => Err(Error::not_found(format!(
            "`{}.{field}` is not a File field",
            table.name
        ))),
    }
}

/// The store-wide access floor from the store's stored definition, `None` for a
/// store with no definition row (an ephemeral `--file-store`) — the same answer
/// the admin file endpoints resolve.
async fn store_floor(cat: &Catalog, store: &str) -> Result<Option<u8>> {
    Ok(load_file_store_by_name(cat, store)
        .await?
        .and_then(|def| def.min_role))
}

