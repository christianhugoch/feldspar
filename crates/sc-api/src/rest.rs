//! The REST [`ApiProvider`] (design §13.4).
//!
//! Projects an application's tables into a REST API in the shape the design's
//! quality bar (Hasura / PostgREST / Supabase) sets: a table `posts` becomes
//! `GET /api/posts`, `POST /api/posts`, `PUT /api/posts/{id}`, and
//! `DELETE /api/posts/{id}`. The table is a **literal** path segment, not a
//! `{table}` parameter — an app's API exposes the app's own tables, so they are
//! part of the contract and get typed client methods (`listPosts`, `createPosts`,
//! …) rather than a stringly-typed table argument. That projection is the same
//! [`EndpointSet`](crate::EndpointSet) machinery the admin API uses, so an app's
//! client is generated by the same [`generate_client`](crate::generate_client).
//!
//! **Authorization** comes from each table's own [`AccessRules`](sc_catalog::AccessRules)
//! (§7): reads require `min_role_read`, writes `min_role_write`. The provider
//! enforces the requirement before running anything, so a REST caller sees
//! exactly what a user of that role would — there is no path into the data that
//! skips the check.
//!
//! **Authentication**: the projection includes the app's own `login` / `logout` /
//! `whoami`, so a React app authenticates against `sc-auth` through its own API
//! rather than borrowing the admin's (§7.2). `login` is the one public endpoint —
//! it is how a caller stops being anonymous — and it verifies credentials against
//! the same `sc_auth::authenticate` the admin login uses, for any role rather
//! than admins only. The provider never touches cookies: it returns a
//! [`SessionAction`] and the transport mints and carries the token.
//!
//! **Custom routes** (developer-authored guest code or SQL, §13.4) are carried by
//! the endpoint model and rejected with `501 Not Implemented` at runtime: the
//! MVP stubs them (see `TODO.md` Phase 9), and the honest failure is better than
//! pretending.
//!
//! **Triggers** are projected one endpoint each — `POST {mount}/actions/{name}`,
//! request body → the event's payload, the action's result → the response — but
//! only for the triggers the *application* names ([`project_with`](RestProvider::project_with)).
//! Server-side automation is not an API surface by default: a trigger becomes
//! callable from outside because an app said so, and one nobody named is a 404
//! rather than a 403. Authorization is the trigger's own `min_role`, defaulting
//! to **admin** when it has none — a trigger whose access nobody has thought
//! about must not be the one that turns out to be public.

